#!/usr/bin/env python3
"""Generate schema/pagespec.schema.json (JSON Schema draft-07) from the contracts.

Sources: sections/*.json (content models, variants, allowed motion profiles), templates/templates.json (closed
template enum), tokens/10-semantic/motion.json (motion profiles + const-locked reduced-motion fallbacks).
The schema is a build output: extraction/verify_all.py regenerates it in memory and fails if the file differs.
Run: python3 schema/build_schema.py [--check]
"""
import glob
import json
import os
import sys

DR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(DR, "schema", "pagespec.schema.json")


def _load(rel):
    with open(os.path.join(DR, rel), encoding="utf-8") as f:
        return json.load(f)


def sections():
    out = {}
    for f in sorted(glob.glob(os.path.join(DR, "sections", "*.json"))):
        with open(f, encoding="utf-8") as fh:
            d = json.load(fh)
        out[d["id"]] = d
    return out


def build():
    secs = sections()
    templates = _load("templates/templates.json")["templates"]
    profiles = _load("tokens/10-semantic/motion.json")["profiles"]
    head_budget = _load("extraction/measured-values.json")["copyBudgets"]["head.title"]["budget"]
    branches = []
    for sid in sorted(secs):
        s = secs[sid]
        branches.append({
            "if": {"properties": {"type": {"const": sid}}, "required": ["type"]},
            "then": {"properties": {
                "variant": {"enum": sorted(s["variants"])},
                "content": s["contentModel"],
                "motion": {"properties": {"profile": {"enum": s["motion"]["allowedProfiles"]}}},
            }},
        })
    motion_branches = [{"if": {"properties": {"profile": {"const": pid}}, "required": ["profile"]},
                        "then": {"properties": {"reducedMotionFallback": {"const": p["reducedMotionFallback"]}}}} for pid, p in sorted(profiles.items())]
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": "pagespec.schema.json",
        "$comment": "GENERATED by schema/build_schema.py from sections/*.json, templates/templates.json and tokens/10-semantic/motion.json. Do not hand-edit. maxWords is a custom keyword enforced by schema/semantic_validate.py.",
        "title": "Kestrel design-repo PageSpec",
        "type": "object",
        "additionalProperties": False,
        "required": ["id", "route", "template", "theme", "head", "nodes"],
        "properties": {
            "id": {"type": "string", "pattern": "^page\\.[a-z0-9-]+$"},
            "route": {"type": "string", "pattern": "^/([a-z0-9-]+(/[a-z0-9-]+)*)?$"},
            "template": {"enum": sorted(templates)},
            "theme": {"enum": ["light"]},
            "head": {"$ref": "#/definitions/head"},
            "nodes": {"type": "array", "minItems": 3, "items": {"$ref": "#/definitions/node"}},
        },
        "definitions": {
            "head": {"type": "object", "additionalProperties": False, "required": ["title"], "properties": {"title": {"type": "string", "maxWords": head_budget}}},
            "motion": {
                "type": "object", "additionalProperties": False, "required": ["profile", "reducedMotionFallback"],
                "properties": {"profile": {"enum": sorted(profiles)}, "reducedMotionFallback": {"enum": sorted({p["reducedMotionFallback"] for p in profiles.values()})}},
                "allOf": motion_branches,
            },
            "node": {
                "type": "object", "additionalProperties": False, "required": ["id", "type", "variant", "content", "motion"],
                "properties": {
                    "id": {"type": "string", "pattern": "^[a-z0-9-]+$"},
                    "type": {"enum": sorted(secs)},
                    "variant": {"type": "string"},
                    "content": {"type": "object"},
                    "motion": {"$ref": "#/definitions/motion"},
                },
                "allOf": branches,
            },
        },
    }


if __name__ == "__main__":
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("schema up to date" if ok else "schema OUT OF DATE")
        sys.exit(0 if ok else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote schema/pagespec.schema.json")
